"""The Python implementation of the rpt plugin protocol: the record wire types, the
:func:`records` stream reader, :func:`set_member`, and the plugin entry points :func:`run`,
:func:`main` and :func:`rpt_bin`. Plugins in other languages follow the protocol directly;
this package is a convenience, never a requirement. It uses only the standard library.

The protocol: https://github.com/astr4liteEx/rpt/blob/main/docs/plugin-protocol.md

Versioning: the package's version is rpt's, so 0.2.0 goes with rpt v0.2.0. The record format
is versioned separately by ``schema_version``: adding a field keeps it; renaming or removing
one bumps it after a deprecation release.
"""

